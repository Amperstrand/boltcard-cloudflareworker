#!/usr/bin/env node
import { readFileSync, writeFileSync } from "fs";
import { join } from "path";

const ROOT = import.meta.dirname;
const CSS_FILE = join(ROOT, "..", "public", "static", "css", "tailwind.css");
const OUTPUT = join(ROOT, "..", "static", "tailwind-css.ts");

const css = readFileSync(CSS_FILE, "utf8");
const escaped = css
  .replace(/\\/g, "\\\\")
  .replace(/`/g, "\\`")
  .replace(/\$\{/g, "\\${");

const output = `// Auto-generated by scripts/sync-tailwind-css.mjs — do not edit
export const TAILWIND_CSS = \`${escaped}\`;
`;

writeFileSync(OUTPUT, output);
console.log(`sync-tailwind-css: ${css.length} bytes → static/tailwind-css.ts`);
